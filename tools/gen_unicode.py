"""Writes src/uuid/_unicode.mojo from Python's unicodedata (Unicode 16.0 in CPython 3.14).

The tables mirror what CPython's int() and repr() use: Nd decimal digits, non-printable
codepoints (categories Cc, Cf, Cs, Co, Cn, Zl, Zp, Zs except ASCII space). Run after a
Unicode upgrade: python3 -I tools/gen_unicode.py > src/uuid/_unicode.mojo
"""
import sys
import unicodedata

def runs(pred):
    out, start = [], None
    for c in range(0x110000):
        hit = pred(c)
        if hit and start is None:
            start = c
        elif not hit and start is not None:
            out.append((start, c)); start = None
    if start is not None:
        out.append((start, 0x110000))
    return out

nonprint = runs(lambda c: c >= 0x7F and not chr(c).isprintable())
bounds = [b for r in nonprint for b in r]
nd = [c for c in range(128, 0x110000) if unicodedata.category(chr(c)) == "Nd"]
starts = [c for c in nd if c - 1 not in nd or int(unicodedata.digit(chr(c))) == 0]
assert all(int(unicodedata.digit(chr(s + i))) == i for s in starts for i in range(10))

def table(name, vals, per=12):
    lines = [f"comptime {name}: Array[UInt32, {len(vals)}] = ["]
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(hex(v) for v in vals[i:i + per]) + ",")
    lines.append("]")
    return "\n".join(lines)

print(f'''"""Unicode {unicodedata.unidata_version} tables for CPython-style int() and repr(); generated by tools/gen_unicode.py."""
from std.builtin.globals import global_constant
from std.collections import Array

{table("_NONPRINTABLE", bounds)}

{table("_DECIMAL_STARTS", starts)}


def _upper_bound[n: Int](ref table: Array[UInt32, n], cp: Int) -> Int:
    """Number of table entries <= cp (table is sorted)."""
    var lo = 0
    var hi = n
    while lo < hi:
        var mid = (lo + hi) >> 1
        if Int(table[mid]) <= cp:
            lo = mid + 1
        else:
            hi = mid
    return lo


def is_printable(cp: Int) -> Bool:
    """Whether str.isprintable() accepts one codepoint."""
    if cp < 0x7F:
        return cp >= 32
    ref table = global_constant[_NONPRINTABLE]()
    return (_upper_bound(table, cp) & 1) == 0


def decimal_digit(cp: Int) -> Int:
    """Value 0-9 of an ASCII or Unicode Nd codepoint, else -1."""
    if cp < 128:
        return cp - 48 if cp >= 48 and cp <= 57 else -1
    ref table = global_constant[_DECIMAL_STARTS]()
    var i = _upper_bound(table, cp)
    if i == 0:
        return -1
    var d = cp - Int(table[i - 1])
    return d if d < 10 else -1


def is_space(cp: Int) -> Bool:
    """Whitespace int() strips: ASCII 9-13 and 32, plus non-ASCII Unicode spaces (not U+001C-U+001F)."""
    return (cp >= 9 and cp <= 13) or cp == 32 or cp == 0x85 or cp == 0xA0 or cp == 0x1680 or (cp >= 0x2000 and cp <= 0x200A) or cp == 0x2028 or cp == 0x2029 or cp == 0x202F or cp == 0x205F or cp == 0x3000''')
